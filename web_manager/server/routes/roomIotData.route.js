const express = require('express');
const isAuthenticated = require('../middlewares/authenticate.js');
const data = require('../controllers/roomIotData.controller.js');

const router = express.Router();
router.use(isAuthenticated);
router.put('/devices/:deviceId', data.updateDevice);
router.post('/devices/:deviceId/actuators/:actuatorId/commands', data.controlActuator);
router.post('/rooms/:roomId/controls/actuator', data.controlRoomActuators);
router.get('/devices/:deviceId/sensors', data.listSensors);
router.post('/devices/:deviceId/sensors', data.createSensor);
router.put('/sensors/:sensorId', data.updateSensor);
router.delete('/sensors/:sensorId', data.deleteSensor);
router.get('/devices/:deviceId/actuators', data.listActuators);
router.post('/devices/:deviceId/actuators', data.createActuator);
router.put('/actuators/:actuatorId', data.updateActuator);
router.delete('/actuators/:actuatorId', data.deleteActuator);
router.get('/sensors/:sensorId/readings', data.listReadings);
router.post('/sensors/:sensorId/readings', data.createReading);
router.get('/rooms/:roomId/alerts', data.listAlerts);
router.get('/rooms/:roomId/dashboard-widgets', data.listDashboardWidgets);
router.post('/rooms/:roomId/dashboard-widgets', data.saveDashboardWidget);
router.put('/rooms/:roomId/dashboard-widgets/:widgetId', data.saveDashboardWidget);
router.delete('/rooms/:roomId/dashboard-widgets/:widgetId', data.deleteDashboardWidget);
router.get('/rooms/:roomId/analytics', data.roomAnalytics);
router.post('/alerts/:alertId/acknowledge', data.acknowledgeAlert);
router.get('/devices/:deviceId/commands', data.listCommands);
router.post('/commands/:commandId/complete', data.completeCommand);
router.get('/rooms/:roomId/audit-logs', data.listAuditLogs);
module.exports = router;
